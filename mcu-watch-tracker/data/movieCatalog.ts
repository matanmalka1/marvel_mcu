export const TITLE_KIND_LABELS: Record<TitleKind, string> = {
  movie: "סרט",
  series: "סדרה",
  special: "ספיישל",
};

/** Movies are always tracked; series and specials only when the viewer opts in. */
export function isTitleIncluded(movie: MovieSummary, includeSeries: boolean): boolean {
  return includeSeries || movie.kind === "movie";
}

const ORDERED_TITLES: Record<
  OrderMode,
  Record<"all" | "movies", readonly MovieSummary[]>
> = {
  timeline: {
    all: MOVIES_IN_TIMELINE_ORDER,
    movies: MOVIES_IN_TIMELINE_ORDER.filter((movie) => movie.kind === "movie"),
  },
  release: {
    all: MOVIES_IN_RELEASE_ORDER,
    movies: MOVIES_IN_RELEASE_ORDER.filter((movie) => movie.kind === "movie"),
  },
};

/** The tracked titles, in the viewer's chosen order. Precomputed, so it is referentially stable. */
export function getOrderedTitles(
  orderMode: OrderMode,
  includeSeries: boolean,
): readonly MovieSummary[] {
  return ORDERED_TITLES[orderMode][includeSeries ? "all" : "movies"];
}
